import io
import json
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

from msikb import protocol
from msikb.capture import (
    CaptureError,
    decode_packet,
    decode_packets,
    infer_keymap_from_captures,
    lit_colors,
    packets_from_file,
    parse_hex_text,
    parse_tsv,
)
from msikb.cli import main

FIXTURES = Path(__file__).resolve().parent / "fixtures" / "learn"


def frame_for(msi_code, rgb=(255, 0, 0)):
    region = protocol.KEYCODE_REGION[msi_code]
    return protocol.build_region_frame(region, {msi_code: rgb})


def hex_line(data: bytes) -> str:
    return " ".join("%02x" % b for b in data)


class HexTextTests(unittest.TestCase):
    def test_parses_plain_lines(self):
        packets = parse_hex_text("0e 00 2a 00\nde ad be ef")
        self.assertEqual(len(packets), 2)
        self.assertEqual(packets[0].payload, bytes([0x0E, 0x00, 0x2A, 0x00]))

    def test_parses_labeled_lines(self):
        packets = parse_hex_text("# comment\nesc: 0e 00 2a 00\n")
        self.assertEqual(packets[0].label, "esc")

    def test_rejects_junk(self):
        with self.assertRaises(CaptureError):
            parse_hex_text("this is not hex")


class TsvTests(unittest.TestCase):
    def test_parses_tshark_fields(self):
        payload = frame_for(41, (18, 52, 86))
        line = "12\t5\t0x030e\t0\t" + ":".join("%02x" % b for b in payload) + "\t\n"
        packets = parse_tsv(line, source="gg.pcapng")
        self.assertEqual(len(packets), 1)
        packet = packets[0]
        self.assertEqual(packet.frame, 12)
        self.assertEqual(packet.device_address, 5)
        self.assertEqual(packet.report_id, 0x0E)
        self.assertEqual(packet.report_type, 0x03)
        self.assertEqual(packet.report_id_from_setup, 0x0E)
        self.assertEqual(packet.payload, payload)

    def test_skips_lines_without_payload(self):
        self.assertEqual(parse_tsv("1\t2\t0x0309\t0\t\t\n"), [])


class DecodeTests(unittest.TestCase):
    def test_decode_frame_and_commit(self):
        packets = [
            parse_hex_text(hex_line(frame_for(82, (0, 0, 255))))[0],
            parse_hex_text(hex_line(protocol.build_commit()))[0],
        ]
        decoded = decode_packets(packets)
        self.assertEqual(decoded[0].kind, "frame")
        self.assertEqual(decoded[1].kind, "commit")
        frame = decoded[0].frame
        self.assertEqual(frame.region, "numpad")
        self.assertTrue(frame.trailer_ok)
        self.assertEqual(lit_colors(decoded), {82: (0, 0, 255)})

    def test_decode_unknown_report_is_reported_not_fatal(self):
        packet = parse_hex_text("0b 00 00 00")[0]
        item = decode_packet(packet)
        self.assertEqual(item.kind, "unknown")
        self.assertIn("report id", item.error)


class InferTests(unittest.TestCase):
    def test_single_key_capture(self):
        packets = parse_hex_text(hex_line(frame_for(41)))
        mapping, problems = infer_keymap_from_captures({"esc": packets})
        self.assertEqual(mapping, {"esc": 41})
        self.assertEqual(problems, [])

    def test_ambiguous_capture_is_reported(self):
        combined = frame_for(41)  # modifiers frame with esc lit
        packets = parse_hex_text(
            hex_line(combined) + "\n" + hex_line(frame_for(4, (0, 255, 0))))
        mapping, problems = infer_keymap_from_captures({"mystery": packets})
        self.assertEqual(mapping, {})
        self.assertEqual(len(problems), 1)
        self.assertIn("ambiguous", problems[0])

    def test_colour_filter_disambiguates(self):
        packets = parse_hex_text(
            hex_line(frame_for(41, (255, 0, 0))) + "\n" + hex_line(frame_for(4, (0, 255, 0))))
        mapping, problems = infer_keymap_from_captures({"esc": packets}, color_filter=(255, 0, 0))
        self.assertEqual(mapping, {"esc": 41})
        self.assertEqual(problems, [])

    def test_duplicate_keycode_is_flagged(self):
        packets = parse_hex_text(hex_line(frame_for(41)))
        mapping, problems = infer_keymap_from_captures({"esc": packets, "escape": packets})
        self.assertEqual(mapping, {"esc": 41})
        self.assertIn("already mapped", problems[0])

    def test_capture_without_frames(self):
        packets = parse_hex_text("0b 00 00 00")
        mapping, problems = infer_keymap_from_captures({"junk": packets})
        self.assertEqual(mapping, {})
        self.assertIn("no 0x0E key frame", problems[0])


class FixturePipelineTests(unittest.TestCase):
    """The synthetic fixtures are generated by tests/fixtures/make_fixtures.py."""

    @classmethod
    def setUpClass(cls):
        if not FIXTURES.is_dir() or not list(FIXTURES.glob("*.txt")):
            raise unittest.SkipTest(
                "fixtures missing; run: python tests/fixtures/make_fixtures.py"
            )

    def test_fixtures_decode_to_expected_colours(self):
        expected = {
            "esc.txt": (41, (255, 0, 0)),
            "a.txt": (4, (0, 255, 0)),
            "kp7.txt": (95, (0, 0, 255)),
        }
        for name, (msi_code, rgb) in expected.items():
            packets = packets_from_file(FIXTURES / name)
            colors = lit_colors(decode_packets(packets))
            self.assertEqual(colors, {msi_code: rgb}, name)

    def test_learn_writes_a_usable_keymap(self):
        with tempfile.TemporaryDirectory() as tmp:
            output = Path(tmp) / "captured.json"
            buffer = io.StringIO()
            with redirect_stdout(buffer):
                status = main([
                    "learn",
                    str(FIXTURES / "esc.txt"),
                    str(FIXTURES / "a.txt"),
                    str(FIXTURES / "kp7.txt"),
                    "--keymap-name", "captured",
                    "--output", str(output),
                ])
            self.assertEqual(status, 0, buffer.getvalue())
            payload = json.loads(output.read_text())
            self.assertEqual(payload["x11_to_msi"]["9"], 41)   # esc
            self.assertEqual(payload["x11_to_msi"]["38"], 4)   # a
            self.assertEqual(payload["x11_to_msi"]["79"], 95)  # kp7


class CliTests(unittest.TestCase):
    def run_cli(self, argv):
        buffer = io.StringIO()
        errors = io.StringIO()
        with redirect_stdout(buffer), redirect_stderr(errors):
            status = main(argv)
        return status, buffer.getvalue() + errors.getvalue()

    def test_keys_listing(self):
        status, output = self.run_cli(["keys", "--aliases"])
        self.assertEqual(status, 0)
        self.assertIn("leftctrl", output)
        self.assertIn("num_row", output)

    def test_set_is_dry_run_by_default(self):
        status, output = self.run_cli(["set", "--color", "00ff00"])
        self.assertEqual(status, 0)
        self.assertIn("Dry run", output)
        self.assertIn("4 region frame(s)", output)

    def test_key_subcommand(self):
        status, output = self.run_cli(["key", "--key", "esc", "--color", "ff0000"])
        self.assertEqual(status, 0)
        self.assertIn("modifiers", output)

    def test_bad_colour_is_an_error(self):
        status, output = self.run_cli(["set", "--color", "nope"])
        self.assertEqual(status, 1)
        self.assertIn("invalid colour", output)

    def test_decode_fixture(self):
        status, output = self.run_cli([
            "decode", str(FIXTURES / "esc.txt"), "--keymap", "reference-gs65",
        ])
        self.assertEqual(status, 0)
        self.assertIn("esc", output)
        self.assertIn("commit/apply", output)

    def test_doctor_returns_status(self):
        status, output = self.run_cli(["doctor"])
        self.assertIn("msikb", output)
        self.assertIn(status, (0, 1))


if __name__ == "__main__":
    unittest.main()
